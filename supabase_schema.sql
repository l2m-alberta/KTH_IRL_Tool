-- (Supabase Dashboard -> SQL Editor -> New Query -> Run)

CREATE TABLE IF NOT EXISTS public.submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  full_name TEXT NOT NULL,
  email TEXT NOT NULL,
  academic_institution TEXT NOT NULL,
  venture_website TEXT NOT NULL DEFAULT '',
  venture_details TEXT NOT NULL,
  crl SMALLINT NOT NULL CHECK (crl BETWEEN 1 AND 9),
  trl SMALLINT NOT NULL CHECK (trl BETWEEN 1 AND 9),
  brl SMALLINT NOT NULL CHECK (brl BETWEEN 1 AND 9),
  iprl SMALLINT NOT NULL CHECK (iprl BETWEEN 1 AND 9),
  tmrl SMALLINT NOT NULL CHECK (tmrl BETWEEN 1 AND 9),
  frl SMALLINT NOT NULL CHECK (frl BETWEEN 1 AND 9)
);

-- Lock down direct public/anon access; only the server-side
-- Vercel functions using SUPABASE_SERVICE_ROLE_KEY can read/write.
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;
